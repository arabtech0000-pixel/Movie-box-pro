/**
 * Returns the verified server catalog.
 * Fetches from `/api/movies` if available, with immediate synchronous fallback.
 */
export async function fetchMumoServerCatalog(): Promise<ServerCatalog> {
  try {
    if (typeof window !== 'undefined') {
      const res = await fetch('/api/movies', { signal: AbortSignal.timeout(2000) });
      if (res.ok) {
        const json = await res.json();
        if (json && Array.isArray(json.data) && json.data.length > 0) {
          const items: MediaItem[] = json.data;
          return {
            movies: items.filter((m) => m.type !== 'tv'),
            series: items.filter((m) => m.type === 'tv'),
            heroBanners: items.slice(0, 8),
          };
        }
      }
    }
  } catch (err) {
    // Immediate fallback to verified server movies
  }

  return {
    movies: MUMO_SERVER_MOVIES.filter((m) => m.type !== 'tv'),
    series: MUMO_SERVER_MOVIES.filter((m) => m.type === 'tv'),
    heroBanners: MUMO_SERVER_MOVIES.slice(0, 8),
  };
}
